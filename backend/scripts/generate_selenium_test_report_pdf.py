def convert_html_to_pdf(html_path, output_pdf_path, screenshot_path):
    options = Options()
    options.add_argument('--headless')
    options.add_argument('--disable-gpu')
    options.add_argument('--no-sandbox')
    options.add_argument('--window-size=1200,1600')

    driver = webdriver.Chrome(options=options)
    abs_html = os.path.abspath(html_path)
    driver.get(f"file:///{abs_html}")

    driver.save_screenshot(screenshot_path)
    print(f"Preview screenshot saved to {screenshot_path}")

    print_params = {
        'landscape': False,
        'displayHeaderFooter': True,
        'headerTemplate': '<div style="font-size: 8pt; font-family: \'Times New Roman\'; width: 100%; display: flex; justify-content: space-between; padding-left: 14mm; padding-right: 14mm; color: #555;"><span>Department of Computer Applications — Amal Jyothi College of Engineering Autonomous</span><span>MediTwin AI</span></div>',
        'footerTemplate': '<div style="font-size: 8pt; font-family: \'Times New Roman\'; width: 100%; display: flex; justify-content: space-between; padding-left: 14mm; padding-right: 14mm; color: #555;"><span>MediTwin AI — Software Testing Lab Report</span><span>Page <span class="pageNumber"></span> of <span class="totalPages"></span></span></div>',
        'printBackground': True,
        'paperWidth': 8.27,  # A4 width
        'paperHeight': 11.69, # A4 height
        'marginTop': 0.7,
        'marginBottom': 0.7,
        'marginLeft': 0.55,
        'marginRight': 0.55,
        'preferCSSPageSize': True
    }

    result = driver.execute_cdp_cmd('Page.printToPDF', print_params)
    pdf_bytes = base64.b64decode(result['data'])

    with open(output_pdf_path, 'wb') as f:
        f.write(pdf_bytes)

    driver.quit()
    print(f"Generated PDF written to {output_pdf_path} ({len(pdf_bytes)} bytes)")

    # Also save copy in root for quick user accessibility
    root_pdf = os.path.abspath(r"d:\SEM 2\A.I\MediTwin\MediTwin_AI_Selenium_Test_Cases_Report.pdf")
    with open(root_pdf, 'wb') as f:
        f.write(pdf_bytes)
    print(f"Also saved root copy to {root_pdf}")


